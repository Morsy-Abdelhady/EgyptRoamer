"""Build Core data/sources.json (the public Sources page) from docs/CONTENT-SOURCES.md.

Reads the "Verified facts and where they were checked" table: each row's claim and its sources (links and names,
with the date checked). Usage: PYTHONUTF8=1 python tools/sources.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
md = open(os.path.join(ROOT, 'docs/CONTENT-SOURCES.md'), encoding='utf-8').read()
part = md.split('## Verified facts and where they were checked', 1)[1].split('\n## ', 1)[0]
rows = []
for line in part.splitlines():
    if not line.startswith('| ') or line.startswith('| Claim') or line.startswith('|---'):
        continue
    cells = [c.strip() for c in line.strip().strip('|').split(' | ')]
    if len(cells) < 2:
        continue
    claim, src = cells[0], ' | '.join(cells[1:])
    if claim.startswith('(Distance not used'):
        continue
    guides = re.findall(r'`(g-[a-z0-9-]+|exp-[a-z0-9-]+)`', claim)
    claim = re.sub(r'\s*\(`[^)]*`[^)]*\)', '', claim).strip()
    checked = (re.search(r'checked (\d{4}-\d{2}-\d{2})', src) or [None, '2026-09-28'])[1]
    links = []
    for m in re.finditer(r'(?:([A-Z][^,;()]*?),\s*)?"?([^"]*?)"?\s*(https?://[^\s;)]+)', src):
        url = m.group(3).rstrip('.,')
        host = re.sub(r'^www\.', '', url.split('/')[2])
        name = {'whc.unesco.org': 'UNESCO World Heritage Centre', 'britannica.com': 'Britannica', 'egymonuments.gov.eg': 'Egypt, Ministry of Tourism and Antiquities', 'sis.gov.eg': 'Egypt State Information Service', 'en.wikipedia.org': 'Wikipedia', 'aljazeera.com': 'Al Jazeera', 'iucngreenlist.org': 'IUCN Green List'}.get(host, host)
        links.append({'name': name, 'url': url})
    if links:
        rows.append({'claim': claim, 'guides': guides, 'links': links, 'checked': checked})
out = os.path.join(ROOT, 'wordpress/wp-content/plugins/egypt-roamer-core/data/sources.json')
json.dump({'_note': 'Generated by tools/sources.py from docs/CONTENT-SOURCES.md. Do not edit by hand.', 'rows': rows}, open(out, 'w', encoding='utf-8', newline='\n'), ensure_ascii=False, indent=1)
print(len(rows), 'rows')
