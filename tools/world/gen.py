"""Write the theme's inc/world-data.php from the prototype's trip "worlds" (proposal 4).

Source: docs/prototypes/journey-v4/world-data.json (WORLDS, IMG as the prototype page holds them at run time),
tools/world/imgmap.json (prototype image key -> Unsplash photo id, matched by picture) and
docs/prototypes/journey-v4/wpick.json (the Wikimedia Commons photos, with author and licence).

Every text is an er_t() literal, so the translation tools collect it (translations: tools/world/align.py and
tools/world/manual.json, merged into tools/i18n/new-strings.json by tools/world/strings.py).

Usage: PYTHONUTF8=1 python tools/world/gen.py
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'wordpress/wp-content/themes/egypt-roamer/inc/world-data.php')
D = json.load(open(os.path.join(ROOT, 'docs/prototypes/journey-v4/world-data.json'), encoding='utf-8'))
IMGMAP = json.load(open(os.path.join(ROOT, 'tools/world/imgmap.json'), encoding='utf-8'))
WPICK = json.load(open(os.path.join(ROOT, 'docs/prototypes/journey-v4/wpick.json'), encoding='utf-8'))
SEEDS = {'valley': 'exp-valley', 'redsea': 'exp-dive', 'white': 'exp-safari', 'nile': 'exp-dinner', 'giza': 'exp-giza',
         'abu': 'exp-abu', 'alex': 'exp-alexandria', 'ras': 'exp-ras-mohammed', 'siwa': 'exp-siwa', 'food': 'exp-food',
         'cruise': 'exp-cruise'}
# The food photos are the Commons files already on the site (inc/ux2-trips.php ER_UX2_COMMONS_CARDS).
COMMONS_FOOD = {
    'c_koshary': ('Egyptian_food_Koshary.jpg', 'Dina Said', 'CC BY-SA 4.0'),
    'c_ful': ('Foul_Mohamed_Ahmed_-_foul.jpg', 'Marsupium', 'CC BY-SA 4.0'),
    'c_hawawshi': ('Hawawshi_Main_1_Mohamed_Moheyeldin.jpg', 'Mohamed Moheyeldin', 'CC BY-SA 4.0'),
    'c_feteer': ('Egyptian-food-16.jpg', 'Mohamed Ouda', 'CC BY-SA 4.0'),
}
UNSPLASH = re.compile(r'(1[5-7]\d{11}-[0-9a-f]{12})')


def q(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'") + "'"


def t(s):
    return 'er_t( ' + q(s) + ' )' if s else "''"


def media(key):
    """[ 'u' => unsplash id ] or [ 'src' => commons url, 'page' => file page ]."""
    if not key:
        return None
    v = D['IMG'].get(key, '')
    m = UNSPLASH.search(v) if not v.startswith('DATA') else None
    if m:
        return {'u': m.group(1)}
    if v == 'DATA' and IMGMAP.get(key):
        return {'u': IMGMAP[key]}
    alias = re.match(r'^img/([a-z_0-9]+)\.jpg$', v)
    if alias and alias.group(1) != key:
        return media(alias.group(1))
    if key in WPICK:
        title = WPICK[key]['title'].replace('File:', '').replace(' ', '_')
        return {'commons': title, 'page': WPICK[key]['page']}
    if key in COMMONS_FOOD:
        f = COMMONS_FOOD[key][0]
        return {'commons': f, 'page': 'https://commons.wikimedia.org/wiki/File:' + f}
    raise SystemExit('no source for image ' + key)


def vid(v):
    return q(v.replace('video/', '').replace('.mp4', '')) if v else "''"


def php_media(m):
    if not m:
        return 'null'
    return '[ ' + ', '.join(f"'{k}' => {q(v)}" for k, v in m.items()) + ' ]'


def chip_token(c, i, sum_=False):
    if re.match(r'^\d+ options( from \d+ partners)?$', c):
        return "'{options}'"
    if c.startswith('Free cancellation'):
        return "'{cancel}'"
    if c in ('Private', 'Private option available', 'Private or small group', 'Small group', 'Small-group option available'):
        return "'{group}'"
    if c.startswith('Pickup'):
        return "'{pickup}'"
    if re.match(r'^(About )?\d+(–\d+)? (hours|days)$', c):
        return "'{length}'"
    return t(c)


def main():
    out = ['<?php', '/**',
           ' * Proposal 4: the trip "worlds" as the prototype has them (docs/prototypes/journey-v4, WORLDS). Generated by',
           ' * tools/world/gen.py from the prototype; do not edit by hand. Every text is from the trip page\'s own body or',
           ' * the prototype\'s headings (owner-approved design, 18 Oct); photos are the prototype\'s (free tagged Unsplash',
           ' * photos and credited Wikimedia Commons files, docs/IMAGE-QUALITY-AUDIT-2026-10-02.md §8); videos are the',
           ' * theme\'s own clips (assets/video). Chips in braces are filled from the partner-stated offer facts.',
           ' */', '', "defined( 'ABSPATH' ) || exit;", '',
           '/** The world of an experience by its seed id (exp-valley…), or [] when it has none. */',
           'function er_world_data( string $seed ): array {', '\tswitch ( $seed ) {']
    for wk, w in D['WORLDS'].items():
        L = []
        L.append(f"\t\tcase '{SEEDS[wk]}':")
        L.append('\t\t\treturn [')
        L.append(f"\t\t\t\t'key'      => '{wk}',")
        L.append(f"\t\t\t\t'cls'      => {q(w['cls'])},")
        L.append(f"\t\t\t\t'fx'       => {q(w['fx'])},")
        L.append(f"\t\t\t\t'photo'    => {php_media(media(w['photo']))},")
        L.append(f"\t\t\t\t'video'    => {vid(w.get('video'))},")
        for k in ('eyebrow', 'lead', 'quote', 'go'):
            L.append(f"\t\t\t\t'{k}' => {t(w.get(k, ''))},")
        L.append(f"\t\t\t\t'j_eyebrow' => {t(w['jEyebrow'])},")
        L.append(f"\t\t\t\t'j_title'   => {t(w['jTitle'])},")
        L.append("\t\t\t\t'steps'    => [")
        for s in w['steps']:
            parts = [f"'t' => {t(s.get('t', ''))}", f"'p' => {t(s.get('p', ''))}", f"'why' => {t(s.get('why', ''))}"]
            parts.append(f"'img' => {php_media(media(s.get('img')))}")
            parts.append(f"'video' => {vid(s.get('video'))}")
            parts.append(f"'credit' => {q(s.get('credit', '') if not s.get('video') else '')}")
            parts.append(f"'wall' => {'true' if s.get('wall') else 'false'}")
            parts.append(f"'tone' => {q(s.get('tone', 'warm'))}")
            L.append('\t\t\t\t\t[ ' + ', '.join(parts) + ' ],')
        L.append('\t\t\t\t],')
        S = w['sec']
        L.append("\t\t\t\t'sec'      => [")
        L.append(f"\t\t\t\t\t'eyebrow' => {t(S['eyebrow'])},")
        L.append(f"\t\t\t\t\t'title'   => {t(S['title'])},")
        L.append("\t\t\t\t\t'ps'      => [ " + ', '.join(t(p) for p in S.get('ps', [])) + ' ],')
        L.append("\t\t\t\t\t'tabs'    => [")
        for g, b, x in S['tabs']:
            L.append(f"\t\t\t\t\t\t[ {q(g)}, {t(b)}, {t(x)} ],")
        L.append('\t\t\t\t\t],')
        L.append(f"\t\t\t\t\t'night'   => {'true' if S.get('night') else 'false'},")
        L.append(f"\t\t\t\t\t'wall'    => {'true' if S.get('wall') else 'false'},")
        L.append('\t\t\t\t],')
        L.append("\t\t\t\t'papy'     => [")
        for p in w['papy']:
            m = p[3] if len(p) > 3 else ''
            if m and m.startswith('img:'):
                key, cap = (m[4:].split('|') + [''])[:2]
                mm = php_media(media(key))
                L.append(f"\t\t\t\t\t[ {t(p[0])}, {t(p[1])}, {t(p[2])}, [ 'img' => {mm}, 'cap' => {q(cap)} ] ],")
            elif m:
                L.append(f"\t\t\t\t\t[ {t(p[0])}, {t(p[1])}, {t(p[2])}, [ 'video' => 'karnak-columns' ] ],")
            else:
                L.append(f"\t\t\t\t\t[ {t(p[0])}, {t(p[1])}, {t(p[2])}, null ],")
        L.append('\t\t\t\t],')
        L.append("\t\t\t\t'faq'      => [")
        for qq, a in w.get('faq') or []:
            L.append(f"\t\t\t\t\t[ {t(qq)}, {t(a)} ],")
        L.append('\t\t\t\t],')
        L.append("\t\t\t\t'chips'    => [ " + ', '.join(chip_token(c, i) for i, c in enumerate(w['chips'])) + ' ],')
        L.append("\t\t\t\t'sum'      => [ " + ', '.join(t(c) if i == 0 else chip_token(c, i, True) for i, c in enumerate(w['sum'])) + ' ],')
        L.append(f"\t\t\t\t'place'    => {t(w.get('place', ''))},")
        L.append(f"\t\t\t\t'stay'     => {t((w.get('stay') or {}).get('title', ''))},")
        picks = [o.get('why', '') for o in w['opts'] if o.get('pick')]
        L.append(f"\t\t\t\t'pick_why' => {t(picks[0] if picks else '')},")
        L.append('\t\t\t];')
        out += L
    out += ['\t}', '\treturn [];', '}', '']
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    print('wrote', OUT)


if __name__ == '__main__':
    main()
