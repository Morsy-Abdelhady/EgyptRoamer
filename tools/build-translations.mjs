// Generate WordPress translation files (.l10n.php, WP 6.5+) for the theme and
// the Core plugin's visitor-facing strings, from:
//   1. the approved prototype's locale files (keys = English source text), and
//   2. tools/i18n/new-strings.json (strings added for WordPress templates — unreviewed).
//
//   node tools/build-translations.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";
import { execFileSync } from "child_process";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const proto = path.join(root, "Egypt Roamer/assets/js");
const theme = path.join(root, "wordpress/wp-content/themes/egypt-roamer");
const plugin = path.join(root, "wordpress/wp-content/plugins/egypt-roamer-core");
const LANGS = { de: ["de_DE", "nplurals=2; plural=(n != 1);"], fr: ["fr_FR", "nplurals=2; plural=(n > 1);"], it: ["it_IT", "nplurals=2; plural=(n != 1);"], es: ["es_ES", "nplurals=2; plural=(n != 1);"], ru: ["ru_RU", "nplurals=3; plural=(n%10==1 && n%100!=11 ? 0 : n%10>=2 && n%10<=4 && (n%100<10 || n%100>=20) ? 1 : 2);"], zh: ["zh_CN", "nplurals=1; plural=0;"], ar: ["ar", "nplurals=6; plural=(n==0 ? 0 : n==1 ? 1 : n==2 ? 2 : n%100>=3 && n%100<=10 ? 3 : n%100>=11 ? 4 : 5);"] };
const ORDER = ["de", "fr", "it", "es", "ru", "zh", "ar"];

const used = JSON.parse(execFileSync("python3", [path.join(root, "tools/i18n-strings.py")], { encoding: "utf8" }));
const extra = JSON.parse(fs.readFileSync(path.join(root, "tools/i18n/new-strings.json"), "utf8")).strings;
const data = await import(pathToFileURL(path.join(proto, "data.js")).href);

const php = (v) => "'" + String(v).replace(/\\/g, "\\\\").replace(/'/g, "\\'") + "'";
const report = [];

for (const code of ORDER) {
  const [locale, plural] = LANGS[code];
  const dict = (await import(pathToFileURL(path.join(proto, `locales/${code}.js`)).href))[code];
  const all = {};
  for (const [k, v] of Object.entries(dict.ui)) all[k] = typeof v === "string" ? v : v.other;
  all["You <em>Feel</em> It"] = dict.html["hero-sub"];
  all["Egypt isn't a checklist.<br />It's a story you <em>step&nbsp;into</em>."] = dict.html["interlude-quote"];
  data.film.forEach((f, i) => {
    const t = dict.content.film?.[i] || {};
    if (t.kicker) all[f.kicker] = t.kicker;
    if (t.caption) all[f.caption] = t.caption;
  });
  const copy = dict.ui["© 2026 Egypt Roamer. Independent travel discovery. All rights reserved."];
  if (copy) all["© {year} Egypt Roamer. Independent travel discovery. All rights reserved."] = copy.replace("2026", "{year}");
  for (const [k, v] of Object.entries(extra)) all[k] = v[ORDER.indexOf(code)];

  for (const [target, domain, keys] of [[theme, "egypt-roamer", used.theme], [plugin, "egypt-roamer-core", used.plugin]]) {
    const messages = {};
    const missing = [];
    for (const k of keys) (all[k] ? (messages[k] = all[k]) : missing.push(k));
    const body = Object.entries(messages).map(([k, v]) => `\t\t${php(k)} => ${php(v)},`).join("\n");
    const out = `<?php\n// Generated by tools/build-translations.mjs — do not edit. Sources: prototype locale files + tools/i18n/new-strings.json.\nreturn [\n\t'domain' => ${php(domain)},\n\t'language' => ${php(locale)},\n\t'plural-forms' => ${php(plural)},\n\t'messages' => [\n${body}\n\t],\n];\n`;
    fs.mkdirSync(path.join(target, "languages"), { recursive: true });
    // Themes load languages/{locale}.l10n.php; plugins load languages/{domain}-{locale}.l10n.php.
    const file = target === theme ? `${locale}.l10n.php` : `${domain}-${locale}.l10n.php`;
    fs.writeFileSync(path.join(target, "languages", file), out);
    report.push(`${domain} ${locale}: ${Object.keys(messages).length}/${keys.length}${missing.length ? " MISSING " + JSON.stringify(missing) : ""}`);
  }
}
console.log(report.join("\n"));
